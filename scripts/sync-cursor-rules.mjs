/**
 * Generates Cursor project rules (.cursor/rules/*.mdc) from GitHub Copilot-style
 * sources under .github/rules/ and .github/instructions/.
 *
 * Run: npm run sync-cursor-rules
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

const SOURCE_DIRS = [
    { dir: ".github/rules", kind: "rule" },
    { dir: ".github/instructions", kind: "instruction" },
];

const OUTPUT_DIR = ".cursor/rules";

/** Relative paths (POSIX) that become alwaysApply: true in Cursor. */
const ALWAYS_APPLY_SOURCES = new Set([".github/rules/main.rule.md"]);

const GENERATED_BODY_PREFIX = `> **Generated file.** Source of truth: \`{{source}}\`. Regenerate with \`npm run sync-cursor-rules\` — do not edit this file directly.\n\n`;

const FRONTMATTER_RE = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/;

/**
 * @param {string} raw
 * @returns {{ frontmatter: Record<string, string>, body: string }}
 */
function parseMarkdownWithFrontmatter(raw) {
    const match = raw.match(FRONTMATTER_RE);
    if (!match) {
        throw new Error("Expected YAML frontmatter delimited by ---");
    }

    /** @type {Record<string, string>} */
    const frontmatter = {};
    for (const line of match[1].split(/\r?\n/)) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith("#")) {
            continue;
        }
        const colon = trimmed.indexOf(":");
        if (colon === -1) {
            continue;
        }
        const key = trimmed.slice(0, colon).trim();
        let value = trimmed.slice(colon + 1).trim();
        if (
            (value.startsWith('"') && value.endsWith('"')) ||
            (value.startsWith("'") && value.endsWith("'"))
        ) {
            value = value.slice(1, -1);
        }
        frontmatter[key] = value;
    }

    return { frontmatter, body: match[2] };
}

/**
 * @param {Record<string, string>} fields
 */
function serializeFrontmatter(fields) {
    const lines = ["---"];
    for (const [key, value] of Object.entries(fields)) {
        const needsQuotes = /[:#,\n]/.test(value) || value.includes("*");
        lines.push(needsQuotes ? `${key}: "${value}"` : `${key}: ${value}`);
    }
    lines.push("---", "");
    return lines.join("\n");
}

/**
 * @param {string} sourceRelative POSIX path from repo root
 * @param {{ frontmatter: Record<string, string>, body: string }} parsed
 */
function buildMdc(sourceRelative, parsed) {
    const alwaysApply = ALWAYS_APPLY_SOURCES.has(sourceRelative);

    /** @type {Record<string, string>} */
    const outFm = {};
    if (parsed.frontmatter.description) {
        outFm.description = parsed.frontmatter.description;
    }
    if (parsed.frontmatter.applyTo) {
        outFm.globs = parsed.frontmatter.applyTo;
    }
    outFm.alwaysApply = alwaysApply ? "true" : "false";

    const banner = GENERATED_BODY_PREFIX.replace("{{source}}", sourceRelative);
    return serializeFrontmatter(outFm) + banner + parsed.body.replace(/^\s+/, "");
}

/**
 * @returns {string[]} POSIX paths under repo root
 */
function listMarkdownSources() {
    /** @type {string[]} */
    const sources = [];

    for (const { dir } of SOURCE_DIRS) {
        const absDir = path.join(repoRoot, dir);
        if (!fs.existsSync(absDir)) {
            console.warn(`skip missing directory: ${dir}`);
            continue;
        }
        for (const name of fs.readdirSync(absDir)) {
            if (!name.endsWith(".md")) {
                continue;
            }
            sources.push(path.posix.join(dir.replace(/\\/g, "/"), name));
        }
    }

    return sources.sort();
}

function outputBasename(sourceRelative) {
    return sourceRelative.replace(/^\.github\/(rules|instructions)\//, "").replace(/\.md$/, ".mdc");
}

/**
 * Remove previously generated .mdc files that are no longer produced from sources.
 * @param {Set<string>} expectedOutputNames basename only
 */
function removeStaleOutputs(expectedOutputNames) {
    const outDir = path.join(repoRoot, OUTPUT_DIR);
    if (!fs.existsSync(outDir)) {
        return;
    }
    for (const name of fs.readdirSync(outDir)) {
        if (!name.endsWith(".mdc")) {
            continue;
        }
        if (expectedOutputNames.has(name)) {
            continue;
        }
        const filePath = path.join(outDir, name);
        const text = fs.readFileSync(filePath, "utf8");
        if (text.includes("**Generated file.**")) {
            fs.unlinkSync(filePath);
            console.log(`removed stale ${path.posix.join(OUTPUT_DIR, name)}`);
        }
    }
}

function main() {
    const sources = listMarkdownSources();
    const expectedOutputs = new Set();

    const outDir = path.join(repoRoot, OUTPUT_DIR);
    fs.mkdirSync(outDir, { recursive: true });

    for (const sourceRelative of sources) {
        const absSource = path.join(repoRoot, ...sourceRelative.split("/"));
        const raw = fs.readFileSync(absSource, "utf8");
        const parsed = parseMarkdownWithFrontmatter(raw);
        const mdc = buildMdc(sourceRelative, parsed);

        const outName = outputBasename(sourceRelative);
        expectedOutputs.add(outName);

        const outPath = path.join(outDir, outName);
        fs.writeFileSync(outPath, mdc.endsWith("\n") ? mdc : `${mdc}\n`, "utf8");
        console.log(`wrote ${path.posix.join(OUTPUT_DIR, outName)}`);
    }

    removeStaleOutputs(expectedOutputs);
    console.log(`synced ${sources.length} rule(s) from .github → ${OUTPUT_DIR}`);
}

main();
